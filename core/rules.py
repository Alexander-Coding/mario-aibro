"""Правила и числа игры в одном месте.

Их читают и живая игра, и среда обучения: если поменять очки здесь,
поменяется и то, что видит игрок, и то, за что учится нейросеть.
"""

from __future__ import annotations

# Фиксированный шаг симуляции. Живая игра крутит тот же шаг через
# аккумулятор, поэтому скорость игры не зависит от FPS машины.
FIXED_DT = 1.0 / 60.0

# Размер тайла уровня. Центры блоков лежат на 32*i + 16.
TILE = 32

# ---------------------------------------------------------------
# ОЧКИ
# ---------------------------------------------------------------

COIN_POINTS = 100
BLOCK_POINTS = 100
ENEMY_POINTS = 100

# Флагшток: доля высоты захвата → очки. Как в Super Mario Bros:
# чем выше схватился, тем больше.
FLAG_TIERS: tuple[tuple[float, int], ...] = (
    (0.95, 5000),
    (0.70, 2000),
    (0.45, 800),
    (0.20, 400),
    (0.00, 100),
)

# За каждую оставшуюся целую секунду таймера после входа в замок
TIME_BONUS_PER_SECOND = 20

# ---------------------------------------------------------------
# УРОВЕНЬ
# ---------------------------------------------------------------

DEFAULT_TIME_LIMIT = 200.0

# Ниже этой высоты — упал в пропасть
DEATH_Y = -100

# Враги оживают, когда игрок подходит ближе этого расстояния по X
# (как в оригинале: враг начинает идти, когда появился на экране).
ENEMY_ACTIVATION_DISTANCE = 900

# ---------------------------------------------------------------
# ФИНИШ
# ---------------------------------------------------------------

# Скорость съезда по флагштоку, пикселей за кадр
FLAG_SLIDE_SPEED = 4

# Пауза внизу флагштока перед прыжком к замку, кадров
FLAG_HOLD_FRAMES = 20

# Страховка: сколько кадров максимум идём к двери замка
CASTLE_WALK_MAX_FRAMES = 900

# Сколько кадров после удара игрок не управляет горизонталью
# (отброс от врага не должен гаситься первой же нажатой клавишей)
KNOCKBACK_FRAMES = 12


def flag_points(fraction: float) -> int:
    """Очки за флагшток по доле высоты захвата 0..1."""

    for threshold, points in FLAG_TIERS:
        if fraction >= threshold:
            return points

    return FLAG_TIERS[-1][1]
